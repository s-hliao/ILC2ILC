#!/usr/bin/env python3
"""Writes test/fk_reference.h: foot-site positions in the trunk frame from MuJoCo (Menagerie unitree_go1/go1.xml) at
random joint angles, the reference go1_core.h's leg kinematics are tested against. Run where mujoco and the Menagerie
are (the ilc_quad container): python3 gen_fk_reference.py <go1.xml> <out.h>"""
import sys

import mujoco
import numpy as np

m = mujoco.MjModel.from_xml_path(sys.argv[1])
d = mujoco.MjData(m)
rng = np.random.default_rng(1)
legs = ["FL", "FR", "RL", "RR"]
rows = []
for _ in range(20):
    q = np.concatenate([[rng.uniform(-0.8, 0.8), rng.uniform(-0.6, 3.0), rng.uniform(-2.7, -0.9)] for _ in legs])
    d.qpos[:] = 0.0
    d.qpos[3] = 1.0                                   # trunk at the origin, identity orientation
    for i, leg in enumerate(legs):
        for j, part in enumerate(("hip", "thigh", "calf")):
            d.qpos[m.jnt_qposadr[mujoco.mj_name2id(m, mujoco.mjtObj.mjOBJ_JOINT, f"{leg}_{part}_joint")]] = q[3 * i + j]
    mujoco.mj_kinematics(m, d)
    trunk = d.xpos[mujoco.mj_name2id(m, mujoco.mjtObj.mjOBJ_BODY, "trunk")]
    feet = [d.site_xpos[mujoco.mj_name2id(m, mujoco.mjtObj.mjOBJ_SITE, leg)] - trunk for leg in legs]
    rows.append((q, np.array(feet)))
with open(sys.argv[2], "w") as f:
    f.write("// generated by scripts/gen_fk_reference.py from Menagerie unitree_go1/go1.xml: q (canonical) -> feet (trunk frame)\n")
    f.write("#pragma once\nstatic const int FK_N = %d;\nstatic const double FK_Q[%d][12] = {\n" % (len(rows), len(rows)))
    f.write(",\n".join("{" + ", ".join("%.9f" % v for v in q) + "}" for q, _ in rows) + "};\n")
    f.write("static const double FK_FEET[%d][4][3] = {\n" % len(rows))
    f.write(",\n".join("{" + ", ".join("{" + ", ".join("%.9f" % v for v in p) + "}" for p in P) + "}" for _, P in rows) + "};\n")
